// Generates supabase/seed.sql from src/lib/content/seed.ts (Node >= 23 strips TS types natively).
// Deterministic UUIDs: md5('<seed id>')::uuid, so re-running the seed is idempotent.
import { writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const { seed } = await import(pathToFileURL(path.join(root, "src/lib/content/seed.ts")).href);

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
// Same value as Postgres md5('<id>')::uuid — computed in JS so jsonb references can use it too.
const uuidFor = (v) => {
  const h = createHash("md5").update(v).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
};
const id = (v) => (v ? `${q(uuidFor(v))}::uuid` : "null");
// homepage jsonb: rewrite seed media ids (e.g. "ig-rw-04") to their database uuids
const remapMediaIds = (o) => JSON.parse(JSON.stringify(o), (k, v) =>
  typeof v === "string" && /mediaid$/i.test(k) ? uuidFor(v) : v);
const arr = (a) => `array[${a.map(q).join(",")}]::text[]`;
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;
const out = [];
const add = (table, cols, rows, conflict = "id") => {
  if (!rows.length) return;
  out.push(`insert into public.${table} (${cols.join(", ")}) values\n  ${rows.map((r) => `(${r.join(", ")})`).join(",\n  ")}\non conflict (${conflict}) do nothing;\n`);
};

out.push("-- GENERATED by scripts/generate-seed.mjs from src/lib/content/seed.ts — do not edit by hand.\n");
out.push("-- Sources: docs/research/references.md and docs/research/owner-decisions.md\n\n");

// settings: one row per top-level key
add("site_settings", ["key", "value"], Object.entries(seed.settings).map(([k, v]) => [q(`site.${k.replace(/[A-Z]/g, (c) => "_" + c.toLowerCase())}`), json(v)]), "key");

add("media_assets",
  ["id", "external_url", "kind", "alt_text", "credit", "source_url", "category", "permission_status", "permission_note"],
  seed.media.map((m) => [id(m.id), q(m.url), q(m.kind), q(m.alt), q(m.credit), q(m.sourceUrl), q(m.category),
    q(m.url.startsWith("http") ? "embed_only" : "owner_approved"),
    q(m.url.startsWith("http") ? "YouTube thumbnail of New Life Rwanda video (OD-6)" : "Owner approved use of @newlifeglobalaz photos on 2026-11-19 (OD-6)")]));

add("leadership", ["id", "slug", "name", "title", "role_group", "bio", "photo_id", "instagram", "needs_review", "sort_order", "status"],
  seed.leaders.map((l) => [id(l.id), q(l.slug), q(l.name), q(l.title), q(l.roleGroup), q(l.bio), id(l.photo?.id), q(l.instagram), String(l.needsReview), String(l.sortOrder), "'published'"]));

add("ministries", ["id", "slug", "name", "tagline", "summary", "description", "image_id", "meeting_schedule", "location", "contact_email", "activities", "join_url", "sort_order", "status"],
  seed.ministries.map((x) => [id(x.id), q(x.slug), q(x.name), q(x.tagline), q(x.summary), q(x.description), id(x.image?.id), q(x.meetingSchedule), q(x.location), q(x.contactEmail), arr(x.activities), q(x.joinUrl), String(x.sortOrder), "'published'"]));

add("ministry_leaders", ["ministry_id", "leadership_id", "role_title"],
  seed.ministries.flatMap((x) => x.leaders.map((l) => [id(x.id), id(l.leader.id), q(l.roleTitle)])), "ministry_id, leadership_id");

add("sermon_categories", ["id", "slug", "name", "sort_order"], seed.sermonCategories.map((c, i) => [id(c.id), q(c.slug), q(c.name), String(i)]));

add("sermons", ["id", "slug", "title", "speaker_id", "speaker_name", "description", "scripture", "series", "category_id", "video_url", "audio_url", "preached_on", "is_featured", "source_note", "status", "published_at"],
  seed.sermons.map((s) => [id(s.id), q(s.slug), q(s.title), id(s.speaker?.id), q(s.speakerName), q(s.description), q(s.scripture), q(s.series), id(s.category?.id), q(s.videoUrl), q(s.audioUrl), q(s.preachedOn), String(s.isFeatured), q(s.sourceNote), "'published'", s.preachedOn ? `${q(s.preachedOn)}::timestamptz` : "now()"]));

add("events", ["id", "slug", "title", "summary", "description", "category", "starts_at", "ends_at", "venue", "address", "registration_url", "image_id", "is_featured", "status"],
  seed.events.map((e) => [id(e.id), q(e.slug), q(e.title), q(e.summary), q(e.description), q(e.category), q(e.startsAt), q(e.endsAt), q(e.venue), q(e.address), q(e.registrationUrl), id(e.image?.id), String(e.isFeatured), "'published'"]));

add("gallery_categories", ["id", "slug", "name", "sort_order"], seed.galleryCategories.map((c, i) => [id(c.id), q(c.slug), q(c.name), String(i)]));

add("gallery_items", ["id", "media_id", "category_id", "title", "caption", "sort_order", "status"],
  seed.gallery.map((g, i) => [id(g.id), id(g.media.id), id(g.category?.id), q(g.title), q(g.caption), String(i), "'published'"]));

add("announcements", ["id", "title", "body", "link_url", "link_label", "is_pinned", "status"],
  seed.announcements.map((a) => [id(a.id), q(a.title), q(a.body), q(a.linkUrl), q(a.linkLabel), String(a.isPinned), "'published'"]));

add("homepage_sections", ["key", "kicker", "title", "body", "data", "sort_order", "is_visible"],
  seed.homepage.map((h) => [q(h.key), q(h.kicker), q(h.title), q(h.body), json(remapMediaIds(h.data)), String(h.sortOrder), String(h.isVisible)]), "key");

await writeFile(path.join(root, "supabase", "seed.sql"), out.join("\n"));
console.log(`supabase/seed.sql written (${out.length - 2} insert statements)`);
